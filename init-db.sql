-- =============================================
-- PARROTO BACKEND - DATABASE INITIALIZATION
-- =============================================
-- This script runs automatically (as /docker-entrypoint-initdb.d/01-init.sql) the first
-- time PostgreSQL starts in Docker with an empty volume. It creates the schema and seed
-- data of each microservice database (Database per Service pattern).
--
-- The 5 roles (auth_user, content_user, ...) and their databases are created BEFORE this
-- file by initdb/00-roles.sh, which reads the passwords from environment variables
-- (*_DB_PASSWORD in .env) — no password is hard-coded here (X-04).

-- ========================================
-- AUTH_DB SCHEMA
-- ========================================
\c auth_db auth_user

CREATE TABLE "user" (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email VARCHAR(255) UNIQUE NOT NULL,
  password_hash VARCHAR(255),
  auth_provider VARCHAR(50) NOT NULL DEFAULT 'email', -- email|google|apple
  cefr_level VARCHAR(2) NOT NULL DEFAULT 'B1', -- A1|A2|B1|B2|C1|C2
  total_hours_learned DECIMAL DEFAULT 0,
  total_words_learned INTEGER DEFAULT 0,
  avatar_url TEXT,
  is_active BOOLEAN DEFAULT true,
  last_login_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_user_email ON "user"(email);
CREATE INDEX idx_user_cefr_level ON "user"(cefr_level);
CREATE INDEX idx_user_created_at ON "user"(created_at DESC);
CREATE INDEX idx_user_is_active ON "user"(is_active);

-- Trigger to auto-update updated_at
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_user_updated_at
BEFORE UPDATE ON "user"
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

GRANT CONNECT ON DATABASE auth_db TO auth_user;
GRANT USAGE ON SCHEMA public TO auth_user;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO auth_user;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO auth_user;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO auth_user;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO auth_user;

