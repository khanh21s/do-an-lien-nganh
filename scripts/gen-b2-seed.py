#!/usr/bin/env python3
"""Generate scripts/migrations/002_seed_b2_deck.sql from data/vocab/b2-essential.tsv.

The TSV (header: word, pos, meaning, ipa, example, example_vi) is the reviewed source of
truth for the free public deck "Từ vựng B2 thiết yếu". It was built from
english_b2_2000_anki.tsv (2000 rows) by dropping ~1280 non-words and placeholder
meanings, correcting parts of speech and writing missing meanings/examples/IPA.

Usage:  python3 scripts/gen-b2-seed.py            # validate + write the SQL
        python3 scripts/gen-b2-seed.py --check    # validate only
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "vocab" / "b2-essential.tsv"
OUT = ROOT / "scripts" / "migrations" / "002_seed_b2_deck.sql"

DECK_ID = "22222222-2222-2222-2222-222222222204"
DECK_NAME = "Từ vựng B2 thiết yếu"
DECK_DESC = "Từ vựng, cụm động từ và từ phái sinh trình độ B2 thường gặp trong học thuật và công việc."
HEADER = ["word", "pos", "meaning", "ipa", "example", "example_vi"]
POS_OK = re.compile(r"^(n|v|adj|adv|conj|prep|phr)(/(n|v|adj|adv|conj|prep))?$")


def load():
    with SRC.open(encoding="utf-8") as f:
        rows = list(csv.reader(f, delimiter="\t", quoting=csv.QUOTE_NONE))
    if rows[0] != HEADER:
        sys.exit(f"bad header: {rows[0]}")
    return rows[1:]


def validate(rows):
    errors, seen = [], set()
    for i, r in enumerate(rows, start=2):
        if len(r) != 6:
            errors.append(f"line {i}: {len(r)} columns")
            continue
        word, pos, meaning, ipa, example, example_vi = (c.strip() for c in r)
        key = word.lower()
        if key in seen:
            errors.append(f"line {i}: duplicate '{word}'")
        seen.add(key)
        if not POS_OK.match(pos):
            errors.append(f"line {i}: bad pos '{pos}' for '{word}'")
        if not meaning or not example or not example_vi:
            errors.append(f"line {i}: empty meaning/example/example_vi for '{word}'")
        if pos != "phr" and not re.fullmatch(r"/[^/]+/", ipa):
            errors.append(f"line {i}: bad ipa '{ipa}' for '{word}'")
        if "B2" in meaning:
            errors.append(f"line {i}: placeholder meaning for '{word}'")
        # phrases: irregular verbs change the first word (came across), so check the rest;
        # single words: compare a stem so inflections (denied, studies) still match
        parts = key.split()
        probe = " ".join(parts[1:]) if len(parts) > 1 else parts[0][: max(3, len(parts[0]) - 3)]
        if probe not in example.lower():
            errors.append(f"line {i}: example does not use '{word}'")
    return errors


def q(s):
    s = s.strip()
    return "NULL" if not s else "'" + s.replace("'", "''") + "'"


def render(rows):
    values = ",\n".join(
        f"  ({q(w)}, {q(m)}, {q(e)}, {q(ev)}, {q(ipa)}, {q(p)})"
        for w, p, m, ipa, e, ev in rows
    )
    return f"""-- =============================================================================
-- Free public deck "{DECK_NAME}" ({len(rows)} cards, level B2).
-- GENERATED by scripts/gen-b2-seed.py from data/vocab/b2-essential.tsv - do not edit.
-- Idempotent: the deck has a fixed id and a card is only inserted when the deck has no
-- card with the same word, so re-running never duplicates cards.
--
-- Existing DB:
--   docker exec -i parroto-postgres psql -U parroto -d vocabulary_db -v ON_ERROR_STOP=1 \\
--     < scripts/migrations/002_seed_b2_deck.sql
-- Fresh volumes run it automatically (initdb/02-seed-b2-vocab.sh).
-- =============================================================================
BEGIN;

INSERT INTO vocab_deck (id, name, description, level, is_pro_only, card_count)
VALUES ('{DECK_ID}', {q(DECK_NAME)}, {q(DECK_DESC)}, 'B2', false, 0)
ON CONFLICT (id) DO NOTHING;

INSERT INTO vocab_card (deck_id, word, meaning, example, example_vi, ipa, part_of_speech)
SELECT '{DECK_ID}', v.word, v.meaning, v.example, v.example_vi, v.ipa, v.pos
FROM (VALUES
{values}
) AS v(word, meaning, example, example_vi, ipa, pos)
WHERE NOT EXISTS (
  SELECT 1 FROM vocab_card c
  WHERE c.deck_id = '{DECK_ID}' AND lower(c.word) = lower(v.word)
);

UPDATE vocab_deck
SET card_count = (SELECT count(*) FROM vocab_card WHERE deck_id = '{DECK_ID}')
WHERE id = '{DECK_ID}';

COMMIT;
"""


def main():
    rows = [[c.strip() for c in r] for r in load()]
    errors = validate(rows)
    if errors:
        print("\n".join(errors))
        sys.exit(f"{len(errors)} validation error(s)")
    print(f"{len(rows)} rows OK")
    if "--check" not in sys.argv:
        OUT.write_text(render(rows), encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
