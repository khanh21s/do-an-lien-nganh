#!/usr/bin/env python3
"""Generate scripts/migrations/007_seed_toeic_basic_deck.sql from data/vocab/toeic-co-ban.txt.

The source ("LỚP CƠ BẢN — 238 thẻ", lines "N. phrase | /ipa/ | nghĩa") is kept as provided;
the corrections below are applied here so they stay reviewable:
  - IPA typos (əˈcaʊnt → əˈkaʊnt, stray spaces, "get a loan" carried "take out /").
  - #186 "fringe benefits" duplicates #75 "fringe benefit": dropped.
  - Slash alternatives are split into separate cards, so each card has one answer to type in
    the "Dịch nhanh" game (same meaning → the other one is accepted too):
      #215 Take/Have a look at → "take a look at", "have a look at";
      #229 make an arrangement / agreement / contract → three cards.
  - #225 "suffer from jet lag / air sick": the jet lag part is #137, keep "be airsick".

Usage:  python3 scripts/gen-toeic-seed.py            # validate + write the SQL
        python3 scripts/gen-toeic-seed.py --check    # validate only
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "vocab" / "toeic-co-ban.txt"
OUT = ROOT / "scripts" / "migrations" / "007_seed_toeic_basic_deck.sql"

DECK_ID = "22222222-2222-2222-2222-222222222205"
DECK_NAME = "TOEIC cơ bản – Cụm từ thông dụng"
DECK_DESC = ("Cụm từ TOEIC thường gặp: công sở, họp hành, nhân sự, mua sắm, du lịch, "
             "ngân hàng, sức khỏe và mẫu câu giao tiếp qua điện thoại.")
LEVEL = "B1"
POS = "phrase"
EXPECTED_SOURCE_ROWS = 238

LINE = re.compile(r"^(\d+)\.\s+(.+)$")

# number -> list of replacement rows (word, ipa, meaning); [] drops the row
REPLACE = {
    167: [("get a loan", "/ɡɛt ə ləʊn/", "Nhận một khoản vay")],
    186: [],
    215: [
        ("take a look at", "/teɪk ə lʊk æt/", "Nhìn vào / Xem qua / Xem xét cái gì"),
        ("have a look at", "/hæv ə lʊk æt/", "Nhìn vào / Xem qua / Xem xét cái gì"),
    ],
    225: [("be airsick", "/biː ˈeəsɪk/", "Bị say máy bay")],
    229: [
        ("make an arrangement", "/meɪk ən əˈreɪndʒmənt/", "Thực hiện một sự sắp xếp"),
        ("make an agreement", "/meɪk ən əˈɡriːmənt/", "Đạt được / Thực hiện một thỏa thuận"),
        ("make a contract", "/meɪk ə ˈkɒntrækt/", "Ký / Thực hiện một hợp đồng"),
    ],
}


def fix_ipa(ipa):
    ipa = ipa.replace("əˈcaʊnt", "əˈkaʊnt")
    return re.sub(r"\s+/$", "/", ipa.strip())


def load():
    rows, numbers = [], []
    for raw in SRC.read_text(encoding="utf-8").splitlines():
        m = LINE.match(raw.strip())
        if not m:
            continue
        n = int(m.group(1))
        parts = [p.strip() for p in m.group(2).split(" | ")]
        if len(parts) != 3:
            sys.exit(f"#{n}: expected 'phrase | ipa | meaning', got {parts}")
        numbers.append(n)
        if n in REPLACE:
            rows.extend(REPLACE[n])
        else:
            word, ipa, meaning = parts
            rows.append((word, fix_ipa(ipa), meaning))
    if numbers != list(range(1, EXPECTED_SOURCE_ROWS + 1)):
        sys.exit(f"source must number 1..{EXPECTED_SOURCE_ROWS} without gaps, got {len(numbers)} rows")
    return rows


def validate(rows):
    errors, seen = [], set()
    for word, ipa, meaning in rows:
        key = word.lower()
        if key in seen:
            errors.append(f"duplicate '{word}'")
        seen.add(key)
        if not re.fullmatch(r"/[^/]+/", ipa):
            errors.append(f"bad ipa '{ipa}' for '{word}'")
        if "/" in word:
            errors.append(f"slash in '{word}' (split it into separate cards)")
        if not meaning:
            errors.append(f"empty meaning for '{word}'")
    return errors


def q(s):
    return "'" + s.strip().replace("'", "''") + "'"


def render(rows):
    values = ",\n".join(f"  ({q(w)}, {q(m)}, {q(ipa)})" for w, ipa, m in rows)
    return f"""-- =============================================================================
-- Free public deck "{DECK_NAME}" ({len(rows)} cards, level {LEVEL}).
-- GENERATED by scripts/gen-toeic-seed.py from data/vocab/toeic-co-ban.txt - do not edit.
-- Idempotent: the deck has a fixed id and a card is only inserted when the deck has no
-- card with the same word, so re-running never duplicates cards.
--
-- Existing DB:
--   docker exec -i parroto-postgres psql -U parroto -d vocabulary_db -v ON_ERROR_STOP=1 \\
--     < scripts/migrations/007_seed_toeic_basic_deck.sql
--   docker exec parroto-redis redis-cli --scan --pattern 'vocab:decks:*' | xargs -r docker exec -i parroto-redis redis-cli DEL
-- Fresh volumes run it automatically (initdb/03-seed-toeic-basic.sh).
-- =============================================================================
BEGIN;

INSERT INTO vocab_deck (id, name, description, level, is_pro_only, card_count)
VALUES ('{DECK_ID}', {q(DECK_NAME)}, {q(DECK_DESC)}, '{LEVEL}', false, 0)
ON CONFLICT (id) DO NOTHING;

INSERT INTO vocab_card (deck_id, word, meaning, ipa, part_of_speech)
SELECT '{DECK_ID}', v.word, v.meaning, v.ipa, '{POS}'
FROM (VALUES
{values}
) AS v(word, meaning, ipa)
WHERE NOT EXISTS (
  SELECT 1 FROM vocab_card c
  WHERE c.deck_id = '{DECK_ID}' AND lower(c.word) = lower(v.word)
);

UPDATE vocab_deck
SET card_count = (SELECT count(*) FROM vocab_card WHERE deck_id = '{DECK_ID}')
WHERE id = '{DECK_ID}';

COMMIT;
"""


def main():
    rows = load()
    errors = validate(rows)
    if errors:
        print("\n".join(errors))
        sys.exit(f"{len(errors)} validation error(s)")
    print(f"{len(rows)} cards OK (from {EXPECTED_SOURCE_ROWS} source rows)")
    if "--check" not in sys.argv:
        OUT.write_text(render(rows), encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
