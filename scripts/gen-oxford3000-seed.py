#!/usr/bin/env python3
"""Generate the topical Oxford 3000 vocabulary deck seed from the reviewed TSV.

Usage: python3 scripts/gen-oxford3000-seed.py [--check]
The TSV is generated by import_oxford3000.py, merge_oxford_vietnamese.py, and
translate_oxford_missing.py. Repeated CEFR headwords are stored once at their
lowest listed level; cards are grouped into public decks by topic.
"""
import csv
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data/vocab/oxford3000-topics.tsv"
OUT = ROOT / "scripts/migrations/008_seed_oxford3000.sql"
LEVEL_ORDER = {"A1": 1, "A2": 2, "B1": 3, "B2": 4}
DECK_ID_PREFIX = "22222222-2222-4222-8222-"

POS_LABELS = [
    ("auxiliary v", "auxiliary verb"), ("modal v", "modal verb"),
    ("modal verb", "modal verb"), ("vauxiliary", "auxiliary verb"),
    ("nprep", "noun / preposition"), ("n", "noun"), ("v", "verb"),
    ("adj", "adjective"), ("adv", "adverb"), ("prep", "preposition"),
    ("conj", "conjunction"), ("pron", "pronoun"), ("det", "determiner"),
    ("exclam", "interjection"), ("pro", "pronoun"), ("number", "number"),
]

def q(value):
    if value is None or not str(value).strip():
        return "NULL"
    return "'" + str(value).strip().replace("'", "''") + "'"

def clean_pos(raw):
    text = (raw or "").lower().replace(".", " ").replace("/", " , ")
    labels = []
    for token, label in POS_LABELS:
        if re.search(rf"(?<![a-z]){re.escape(token)}(?![a-z])", text):
            if label not in labels:
                labels.append(label)
            text = re.sub(rf"(?<![a-z]){re.escape(token)}(?![a-z])", " ", text)
    return ", ".join(labels) or "general"

def load():
    with SRC.open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    required = {"word", "part_of_speech", "ipa", "cefr", "topic", "topic_vi", "meaning_vi", "example_en", "example_vi"}
    if not rows or not required.issubset(rows[0]):
        raise SystemExit(f"TSV is missing columns: {sorted(required - set(rows[0] if rows else []))}")
    # The current list repeats some headwords across CEFR bands. Keep the lowest band.
    by_word = {}
    for row in rows:
        word = row["word"].strip()
        if not word or not row["meaning_vi"].strip():
            raise SystemExit(f"Missing word/meaning: {row}")
        key = word.casefold()
        if key not in by_word or LEVEL_ORDER[row["cefr"]] < LEVEL_ORDER[by_word[key]["cefr"]]:
            by_word[key] = row
    return sorted(by_word.values(), key=lambda r: (r["topic"], r["word"].casefold()))

def render(rows):
    topics = sorted({(r["topic"], r["topic_vi"]) for r in rows})
    ids = {topic: DECK_ID_PREFIX + f"{i:012d}" for i, topic in enumerate(topics, 1)}
    counts = Counter(r["topic"] for r in rows)
    deck_values = ",\n".join(
        f"  ('{ids[(topic, topic_vi)]}', {q('Oxford 3000 – ' + topic_vi)}, "
        f"{q(f'Oxford 3000 theo chủ đề {topic_vi}; gồm {counts[topic]} từ, trình độ A1–B2.')}, NULL, false, 0)"
        for topic, topic_vi in topics
    )
    card_values = ",\n".join(
        "  (" + ", ".join([
            q(ids[(r["topic"], r["topic_vi"])]), q(r["word"]), q(r["meaning_vi"]),
            q(r["example_en"]), q(r["example_vi"]), q(r["ipa"]), q(clean_pos(r["part_of_speech"]))
        ]) + ")"
        for r in rows
    )
    return f"""-- =============================================================================
-- Oxford 3000 topical vocabulary seed ({len(rows)} unique headwords, {len(topics)} decks).
-- GENERATED by scripts/gen-oxford3000-seed.py from data/vocab/oxford3000-topics.tsv.
-- Meanings are taken from the Vietnamese vocabulary PDF supplied for this project;
-- unmatched entries use the project's MyMemory English–Vietnamese fallback.
-- Decks and cards are inserted idempotently by fixed deck ID and normalized word.
-- Existing database:
--   docker exec -i parroto-postgres psql -U parroto -d vocabulary_db -v ON_ERROR_STOP=1 \\
--     < scripts/migrations/008_seed_oxford3000.sql
-- Fresh database volumes run it through initdb/04-seed-oxford3000.sh.
-- =============================================================================
BEGIN;

INSERT INTO vocab_deck (id, name, description, level, is_pro_only, card_count)
VALUES
{deck_values}
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  description = EXCLUDED.description,
  level = EXCLUDED.level,
  is_pro_only = EXCLUDED.is_pro_only;

INSERT INTO vocab_card (deck_id, word, meaning, example, example_vi, ipa, part_of_speech)
SELECT v.deck_id::uuid, v.word, v.meaning, v.example, v.example_vi, v.ipa, v.pos
FROM (VALUES
{card_values}
) AS v(deck_id, word, meaning, example, example_vi, ipa, pos)
WHERE NOT EXISTS (
  SELECT 1 FROM vocab_card c
  WHERE c.deck_id = v.deck_id::uuid AND lower(trim(c.word)) = lower(trim(v.word))
);

UPDATE vocab_deck d
SET card_count = (SELECT count(*) FROM vocab_card c WHERE c.deck_id = d.id)
WHERE d.id IN ({', '.join(q(ids[t]) for t in topics)});

COMMIT;
"""

def main():
    rows = load()
    print(f"{len(rows)} unique words, {len({r['topic'] for r in rows})} topical decks; all meanings present")
    if "--check" not in sys.argv:
        OUT.write_text(render(rows), encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
